// Generates installer/generated/languages.nsh from the application catalogs so
// the setup page speaks the same language as the app. NSIS ships translations
// for a defined set of languages; catalogs without a mapping fall back to
// English rather than showing a half-translated window.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const catalogDir = path.join(root, "src", "Hora.Core", "Localization", "locales");
const outDir = path.join(root, "installer", "generated");
const outFile = path.join(outDir, "languages.nsh");

// Catalog id -> NSIS language name understood by MUI_LANGUAGE.
const nsisLanguages = {
  af: "Afrikaans",
  sq: "Albanian",
  ar: "Arabic",
  hy: "Armenian",
  eu: "Basque",
  bs: "Bosnian",
  bg: "Bulgarian",
  ca: "Catalan",
  hr: "Croatian",
  cs: "Czech",
  da: "Danish",
  nl: "Dutch",
  et: "Estonian",
  fa: "Farsi",
  fi: "Finnish",
  fr: "French",
  gl: "Galician",
  ka: "Georgian",
  de: "German",
  el: "Greek",
  he: "Hebrew",
  hu: "Hungarian",
  is: "Icelandic",
  id: "Indonesian",
  ga: "Irish",
  it: "Italian",
  ja: "Japanese",
  ko: "Korean",
  lv: "Latvian",
  lt: "Lithuanian",
  mk: "Macedonian",
  ms: "Malay",
  mn: "Mongolian",
  no: "Norwegian",
  pl: "Polish",
  pt: "Portuguese",
  ro: "Romanian",
  ru: "Russian",
  sr: "Serbian",
  sk: "Slovak",
  sl: "Slovenian",
  es: "Spanish",
  sv: "Swedish",
  th: "Thai",
  "zh-tw": "TradChinese",
  zh: "SimpChinese",
  tr: "Turkish",
  uk: "Ukrainian",
  uz: "Uzbek",
  vi: "Vietnamese",
};

// LangString names used by installer/hora.nsi.
const stringKeys = {
  INSTALLER_WELCOME_INTRO: "installerWelcomeIntro",
  INSTALLER_WELCOME_PRIVACY: "installerWelcomePrivacy",
  INSTALLER_WELCOME_PUBLISHER: "installerWelcomePublisher",
  INSTALLER_RUN_TEXT: "installerRunText",
  INSTALLER_SECTION_APP: "installerSectionApp",
  INSTALLER_SECTION_START: "installerSectionStart",
  INSTALLER_SECTION_DESKTOP: "installerSectionDesktop",
  INSTALLER_SECTION_STARTUP: "installerSectionStartup",
  INSTALLER_SECTION_NAME_START: "installerSectionNameStart",
  INSTALLER_SECTION_NAME_DESKTOP: "installerSectionNameDesktop",
  INSTALLER_SECTION_NAME_STARTUP: "installerSectionNameStartup",
  INSTALLER_ALREADY_INSTALLED: "installerAlreadyInstalled",
  INSTALLER_REQUIRES_WINDOWS10: "installerRequiresWindows10",
  INSTALLER_UNINSTALL_CONFIRM: "installerUninstallConfirm",
  INSTALLER_FINISH_TEXT: "installerFinishText",
  INSTALLER_FINISH_TITLE: "installerFinishTitle",
};

const readCatalog = (id) =>
  JSON.parse(fs.readFileSync(path.join(catalogDir, `${id}.json`), "utf8"));

const english = readCatalog("en");

// NSIS needs $ doubled and quotes escaped; newlines would break a LangString.
const escape = (value) =>
  String(value)
    .replace(/\r?\n/g, " ")
    .replace(/\$/g, "$$$$")
    .replace(/"/g, '$\\"');

const lines = [
  "; Generated by scripts/make-installer-languages.mjs. Do not edit by hand.",
  "; Source: src/Hora.Core/Localization/locales/<id>.json",
  "",
];

const entries = Object.entries(nsisLanguages).map(([id, nsisName]) => {
  const catalog = fs.existsSync(path.join(catalogDir, `${id}.json`))
    ? readCatalog(id)
    : english;
  return { id, nsisName, catalog };
});

// English is always present, even if a mapping ever removes it.
entries.unshift({ id: "en", nsisName: "English", catalog: english });

for (const { nsisName } of entries) {
  lines.push(`!insertmacro MUI_LANGUAGE "${nsisName}"`);
}

lines.push("");

for (const { id, nsisName, catalog } of entries) {
  const macro = nsisName.toUpperCase();
  for (const [name, key] of Object.entries(stringKeys)) {
    const value = String(catalog[key] ?? english[key] ?? "").trim() || english[key];
    lines.push(`LangString ${name} \${LANG_${macro}} "${escape(value)}"`);
  }
  lines.push("");
}

fs.mkdirSync(outDir, { recursive: true });
// NSIS reads non-ASCII scripts reliably only when the file starts with a BOM.
fs.writeFileSync(outFile, "\ufeff" + lines.join("\n"), "utf8");
console.log(
  `Wrote ${path.relative(root, outFile)}: ${entries.length} installer languages, ` +
    `${Object.keys(stringKeys).length} strings each.`,
);
